"""make_splash.py - the boot screen drawn by UEFI SimpleFramebufferDxe (user, 2026-10-14):
black, "EXYNOS WOA" centred with the NTDEV logo (ntdev.png, the user's file) small right below it, and
"Powered by [Windows 11 logo] Windows" at the bottom (where sboot shows "Powered by Android").

    python make_splash.py OUT_DIR [HEADER] -> OUT_DIR/splash.png (preview, 1080x2280) and, with HEADER, the C array
                                            SimpleFramebufferDxe draws (BootSplash.h)

Encoding (decoded by SimpleFramebufferDxe FbDrawBootSplash): per row, little-endian 16-bit tokens until the row is
full: bit 15 clear = that many black pixels; bit 15 set = (token & 0x7FFF) literal pixels follow as B, G, R bytes.

Fonts: Segoe UI from C:\\Windows\\Fonts (rendering happens on the build PC; only pixels go into the firmware).
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

W, H = 1080, 2280
FONTS = r'C:\Windows\Fonts'
BLUE_TOP = (0x4F, 0xC3, 0xF7)     # Windows 11 logo: light-to-deep blue gradient
BLUE_BOTTOM = (0x00, 0x67, 0xC0)


def font(name, size):
    return ImageFont.truetype(os.path.join(FONTS, name), size)


def text_w(draw, text, f):
    l, t, r, b = draw.textbbox((0, 0), text, font=f)
    return r - l


def win11_logo(size):
    """Four squares with a small gap, vertical blue gradient (the Windows 11 mark)."""
    img = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    gap = max(2, size // 22)
    cell = (size - gap) // 2
    grad = Image.new('RGBA', (size, size))
    for y in range(size):
        t = y / (size - 1)
        c = tuple(int(BLUE_TOP[i] + (BLUE_BOTTOM[i] - BLUE_TOP[i]) * t) for i in range(3)) + (255,)
        ImageDraw.Draw(grad).line([(0, y), (size, y)], fill=c)
    mask = Image.new('L', (size, size), 0)
    d = ImageDraw.Draw(mask)
    for ox in (0, cell + gap):
        for oy in (0, cell + gap):
            d.rectangle([ox, oy, ox + cell - 1, oy + cell - 1], fill=255)
    img.paste(grad, (0, 0), mask)
    return img


def make():
    img = Image.new('RGB', (W, H), (0, 0, 0))
    d = ImageDraw.Draw(img)

    title = 'EXYNOS WOA'
    ft = font('segoeuisl.ttf', 112)              # Segoe UI Semilight
    tw = text_w(d, title, ft)
    l, t, r, b = d.textbbox((0, 0), title, font=ft)
    ty = (H - (b - t)) // 2 - t
    d.text(((W - tw) // 2 - l, ty), title, font=ft, fill=(255, 255, 255))

    # NTDEV logo: its own black background is cropped away, then scaled small and centred under the title
    nt = Image.open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'ntdev.png')).convert('RGB')
    nt = nt.crop(nt.point(lambda v: 255 if v > 12 else 0).convert('L').getbbox())
    nw = 190
    nt = nt.resize((nw, nt.height * nw // nt.width), Image.LANCZOS)
    img.paste(nt, ((W - nw) // 2, ty + b + 56))

    # bottom line: "Powered by" small grey, then the logo + "Windows" larger white
    small = font('segoeui.ttf', 34)
    big = font('segoeuisl.ttf', 52)
    logo = 50
    gap1, gap2 = 22, 16
    w1 = text_w(d, 'Powered by', small)
    w2 = text_w(d, 'Windows', big)
    total = w1 + gap1 + logo + gap2 + w2
    x = (W - total) // 2
    base = H - 190                                 # vertical centre of the line
    l, t, r, b = d.textbbox((0, 0), 'Powered by', font=small)
    d.text((x - l, base - (b - t) // 2 - t), 'Powered by', font=small, fill=(0xB0, 0xB0, 0xB0))
    x += w1 + gap1
    img.paste(win11_logo(logo), (x, base - logo // 2), win11_logo(logo))
    x += logo + gap2
    l, t, r, b = d.textbbox((0, 0), 'Windows', font=big)
    d.text((x - l, base - (b - t) // 2 - t), 'Windows', font=big, fill=(255, 255, 255))
    return img


def encode(im):
    px = im.load()
    out = bytearray()
    for y in range(H):
        x = 0
        while x < W:
            n = 0
            if px[x, y] == (0, 0, 0):
                while x < W and px[x, y] == (0, 0, 0):
                    x += 1
                    n += 1
                out += n.to_bytes(2, 'little')
            else:
                lit = bytearray()
                while x < W and px[x, y] != (0, 0, 0):
                    r, g, b = px[x, y]
                    lit += bytes((b, g, r))
                    x += 1
                    n += 1
                out += (0x8000 | n).to_bytes(2, 'little') + lit
    return bytes(out)


def write_header(path, data):
    nl = chr(10)
    with open(path, 'w', newline=nl) as f:
        f.write('// Generated by firmware/tools/bootsplash/make_splash.py - do not edit (see its encoding note).' + nl)
        f.write('#define BOOT_SPLASH_WIDTH   %d%s#define BOOT_SPLASH_HEIGHT  %d%s' % (W, nl, H, nl))
        f.write('STATIC CONST UINT8  mBootSplash[%d] = {%s' % (len(data), nl))
        for i in range(0, len(data), 24):
            f.write('  ' + ', '.join('0x%02x' % b for b in data[i:i + 24]) + ',' + nl)
        f.write('};' + nl)


if __name__ == '__main__':
    out = sys.argv[1] if len(sys.argv) > 1 else '.'
    os.makedirs(out, exist_ok=True)
    im = make()
    im.save(os.path.join(out, 'splash.png'))
    im.resize((W // 2, H // 2), Image.LANCZOS).save(os.path.join(out, 'splash-half.png'))
    if len(sys.argv) > 2:
        data = encode(im)
        write_header(sys.argv[2], data)
        print('header', sys.argv[2], len(data), 'bytes')
    print('ok', os.path.join(out, 'splash.png'))
