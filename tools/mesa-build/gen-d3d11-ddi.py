"""gen-d3d11-ddi.py WDK_D3D10UMDDI_H DEVICE_CPP OUT_DIR - generate the D3D11 DDI glue for Mesa d3d10umd
(notes/gpu-umd-d3d11.md D1): for D3D11DDI_DEVICEFUNCS, every member is assigned either the function d3d10umd already
uses for that member at the D3D10.1 level (same PFN type), a hand-written wrapper (type changed; name D11_<member>),
or a generated stub (new at D3D11). Writes d3d11_stubs.inc (stub definitions, signatures copied from the WDK
typedefs) and d3d11_fill.inc (the assignments). Run again when the table or the WDK changes; the output is
committed with the Mesa patch, this script with exynos-woa.
"""
import re
import sys

hdr = open(sys.argv[1], encoding='utf-8', errors='replace').read()
# members only compiled for the rasterization-only (D3D10PSGP) build are not in our tables
hdr = re.sub(r'#ifdef D3D10PSGP.*?#endif', '', hdr, flags=re.S)
dev = open(sys.argv[2], encoding='utf-8').read()
out = sys.argv[3]


def table(name):
    m = re.search(r'typedef struct ' + name + r'\s*\{(.*?)\}\s*' + name + r'\s*;', hdr, re.S)
    body = re.sub(r'//[^\n]*', '', m.group(1))
    return re.findall(r'(PFND3D\w+)\s+(pfn\w+)\s*;', body)


t101 = {n: t for t, n in table('D3D10_1DDI_DEVICEFUNCS')}
t11 = table('D3D11DDI_DEVICEFUNCS')

# d3d10umd's assignments at the 10.0 level, then the 10.1 overrides
impl = dict(re.findall(r'pDeviceFuncs->(pfn\w+)\s*=\s*(\w+);', dev))
impl.update(dict(re.findall(r'p10_1DeviceFuncs->(pfn\w+)\s*=\s*(\w+);', dev)))


def typedef(pfn):
    m = re.search(r'typedef\s+([\w\s]+?)\s*\(\s*APIENTRY\s*\*\s*' + pfn + r'\s*\)\s*\((.*?)\)\s*;', hdr, re.S)
    if not m:
        raise SystemExit('no typedef for ' + pfn)
    ret = ' '.join(m.group(1).split())
    params = re.sub(r'//[^\n]*', '', m.group(2))
    params = ' '.join(params.split())
    return ret, params


# static in Device.cpp: Device.cpp assigns these members itself after D3D11FillDeviceFuncs
LOCAL = {'DestroyDevice', 'Flush', 'CheckFormatSupport', 'CheckMultisampleQualityLevels', 'SetTextFilterSize'}

stubs, fill, wrapped = [], [], []
for pfn_t, name in t11:
    if name in t101 and t101[name] == pfn_t and name in impl and impl[name] in LOCAL:
        fill.append('   /* f->%s = %s; - set by Device.cpp (static there) */' % (name, impl[name]))
    elif name in t101 and t101[name] == pfn_t and name in impl:
        fill.append('   f->%s = %s;' % (name, impl[name]))
    elif name in t101 and t101[name] != pfn_t:
        fill.append('   f->%s = D11_%s;   /* type changed: %s -> %s */' % (name, name[3:], t101[name], pfn_t))
        wrapped.append(name)
    else:
        ret, params = typedef(pfn_t)
        fn = 'D11Stub_' + name[3:]
        if ret == 'VOID':
            body = '   LOG_UNSUPPORTED_ENTRYPOINT();'
        elif ret == 'SIZE_T':
            body = '   LOG_UNSUPPORTED_ENTRYPOINT();\n   return sizeof(void *);'
        elif ret == 'HRESULT':
            body = '   LOG_UNSUPPORTED_ENTRYPOINT();\n   return E_NOTIMPL;'
        else:
            raise SystemExit('return type %s of %s' % (ret, pfn_t))
        stubs.append('static %s APIENTRY\n%s(%s)\n{\n%s\n}\n' % (ret, fn, params, body))
        fill.append('   f->%s = %s;' % (name, fn))

open(out + '/d3d11_stubs.inc', 'w', newline='\n').write(
    '/* Generated by exynos-woa tools/mesa-build/gen-d3d11-ddi.py from the WDK d3d10umddi.h - do not edit. */\n\n'
    + '\n'.join(stubs))
open(out + '/d3d11_fill.inc', 'w', newline='\n').write(
    '/* Generated by exynos-woa tools/mesa-build/gen-d3d11-ddi.py - do not edit. Wrappers needed: '
    + ', '.join(wrapped) + ' */\n' + '\n'.join(fill) + '\n')
print('%d members: %d same, %d wrapped, %d stubs' % (len(t11), len(t11) - len(wrapped) - len(stubs), len(wrapped),
                                                    len(stubs)))
print('wrappers:', ' '.join(wrapped))
