#!/bin/bash
# recfetch.sh NAME SECONDS [FPS] [LAUNCH [LAUNCHARGS]] - record the phone screen (tools/phone/rec/screenrec/screenrec.exe
# in the user session through run-as-user.ps1 and a generated one-line launcher), fetch the frames to traces/rec/NAME
# and pack them (recpack.py: NAME.gif + NAME-sheet.jpg) for a remote viewer. Run from the repo root.
# notes/g27-x64-apps.md "Remote viewing".
set -u
NAME=${1:?usage: recfetch.sh NAME SECONDS [FPS] [LAUNCH [ARGS]]}; SEC=${2:?seconds}; FPS=${3:-2}; LAUNCH=${4:-}; LARGS=${5:-}
H=$(cd "$(dirname "$0")" && pwd)
EXE=$H/screenrec/screenrec.exe
[ -f "$EXE" ] || { echo "build $EXE first (screenrec/build-screenrec.cmd)"; exit 1; }
OUT=traces/rec/$NAME
mkdir -p "$OUT"; rm -f "$OUT"/frame_*.jpg "$OUT"/frames.txt
run="$OUT/screenrec-run.ps1"
args="'$SEC', '$FPS', '0.5', 'C:\S10eTmp\rec'"
[ -n "$LAUNCH" ] && args="$args, '\"$LAUNCH\"'"
[ -n "$LARGS" ] && args="$args, '\"$LARGS\"'"
printf '%s\r\n' "# generated by tools/phone/rec/recfetch.sh" "Start-Process -Wait -FilePath C:\S10eTmp\screenrec.exe -ArgumentList $args" > "$run"
scp -q -O "$EXE" "$run" s10e:C:/S10eTmp/ < /dev/null || exit 1
ssh s10e 'if exist C:\S10eTmp\rec rmdir /s /q C:\S10eTmp\rec' < /dev/null
ssh s10e "powershell -NoProfile -ExecutionPolicy Bypass -File C:\S10eTmp\run-as-user.ps1 C:\S10eTmp\screenrec-run.ps1 $((SEC + 40))" < /dev/null | tail -1
scp -q -O -r "s10e:C:/S10eTmp/rec/*" "$OUT/" < /dev/null
head -1 "$OUT/frames.txt"; tail -1 "$OUT/frames.txt"
python "$H/recpack.py" "$OUT" "$NAME" "$FPS"
