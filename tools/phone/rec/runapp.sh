#!/bin/bash
# runapp.sh EXE "ARGS" WAIT_S - start EXE with ARGS in the phone's user session (run-as-user.ps1 + a generated one-line
# launcher, like recfetch.sh but without recording) and wait WAIT_S seconds for it. For triage runs that must not
# involve the screen recorder. Run from the repo root. notes/g27-x64-apps.md.
# The long ssh call drops after ~60 s without the phone (ServerAliveInterval): a phone reset mid-run otherwise left
# this script waiting forever (three such leftovers on 2026-10-18).
set -u
EXE=${1:?usage: runapp.sh EXE ARGS WAIT_S}; ARGS=${2:-}; WAIT=${3:-30}
run=$(mktemp)
if [ -n "$ARGS" ]; then line="Start-Process -Wait -FilePath '$EXE' -ArgumentList '$ARGS'"; else line="Start-Process -Wait -FilePath '$EXE'"; fi
printf '%s\r\n' "# generated by tools/phone/rec/runapp.sh" "$line" > "$run"
scp -q -O "$run" s10e:C:/S10eTmp/runapp-run.ps1 < /dev/null && rm -f "$run"
ssh -o ServerAliveInterval=15 -o ServerAliveCountMax=4 s10e "powershell -NoProfile -ExecutionPolicy Bypass -File C:\S10eTmp\run-as-user.ps1 C:\S10eTmp\runapp-run.ps1 $WAIT" < /dev/null | tail -1
